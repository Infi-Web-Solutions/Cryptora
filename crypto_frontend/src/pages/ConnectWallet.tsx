const ConnectWallet = () => {
  const navigate = useNavigate();
  const { toast } = useToast();
  const { connectWallet } = useWallet();
  const [loading, setLoading] = useState(false);

  const handleConnect = async () => {
    setLoading(true);
    try {
      // Check if MetaMask is installed
      if (typeof window.ethereum === 'undefined') {
        toast({
          title: "MetaMask Not Found",
          description: "Please install MetaMask to connect your wallet",
          variant: "destructive"
        });
        setLoading(false);
        return;
      }

      // Request account access
      const accounts = await window.ethereum.request({ 
        method: 'eth_requestAccounts' 
      });
      
      const walletAddress = accounts[0];

      // Connect to backend
      const response = await axios.post(`${API_URL}/auth/connect-wallet`, {
        walletAddress: walletAddress
      }, {
        withCredentials: true
      });

      if (response.data.success) {
        connectWallet(walletAddress);
        
        toast({
          title: "Wallet Connected",
          description: `Wallet ${walletAddress.substring(0, 6)}... connected!`,
        });

        navigate("/portfolio");
      }
    } catch (error: any) {
      console.error("Connection error:", error);
      
      let errorMessage = "Failed to connect wallet";
      if (error.response?.data?.error) {
        errorMessage = error.response.data.error;
      } else if (error.message) {
        errorMessage = error.message;
      }
      
      toast({
        title: "Connection Failed",
        description: errorMessage,
        variant: "destructive"
      });
    } finally {
      setLoading(false);
    }
  };

  const handleAutoRegister = async () => {
    setLoading(true);
    try {
      // Check if MetaMask is installed
      if (typeof window.ethereum === 'undefined') {
        toast({
          title: "MetaMask Not Found",
          description: "Please install MetaMask to register",
          variant: "destructive"
        });
        setLoading(false);
        return;
      }

      // Request account access
      const accounts = await window.ethereum.request({
        method: 'eth_requestAccounts'
      });

      const walletAddress = accounts[0];

      // Check if already registered on-chain
      const provider = new ethers.BrowserProvider(window.ethereum);
      const contractForCheck = new ethers.Contract(CONTRACT_ADDRESS, CONTRACT_ABI, provider);

      const isRegistered = await contractForCheck.registered(walletAddress);
      if (isRegistered) {
        toast({
          title: "Already Registered",
          description: "This wallet is already registered on the blockchain",
          variant: "destructive"
        });
        setLoading(false);
        return;
      }

      // Switch to Sepolia network
      try {
        await provider.send("wallet_switchEthereumChain", [{ chainId: "0xaa36a7" }]);
      } catch (switchError: any) {
        if (switchError.code === 4902) {
          await provider.send("wallet_addEthereumChain", [{
            chainId: "0xaa36a7",
            chainName: "Sepolia",
            nativeCurrency: { name: "SepoliaETH", symbol: "ETH", decimals: 18 },
            rpcUrls: ["https://rpc.sepolia.org"],
            blockExplorerUrls: ["https://sepolia.etherscan.io"]
          }]);
        } else {
          throw switchError;
        }
      }

      // Get signer and call register function directly
      const signer = await provider.getSigner();
      const contract = new ethers.Contract(CONTRACT_ADDRESS, CONTRACT_ABI, signer);

      // Call register function with gas limit to ensure MetaMask shows confirmation
      const tx = await contract.register({ gasLimit: 200000 });
      await tx.wait();

      toast({
        title: "Registration Successful",
        description: "Wallet registered on blockchain successfully!",
      });

      // Now connect to backend
      const response = await axios.post(`${API_URL}/auth/connect-wallet`, {
        walletAddress: walletAddress
      }, {
        withCredentials: true
      });

      if (response.data.success) {
        connectWallet(walletAddress);

        toast({
          title: "Wallet Connected",
          description: `Wallet ${walletAddress.substring(0, 6)}... connected!`,
        });

        navigate("/portfolio");
      }
    } catch (error: any) {
      console.error("Auto-register error:", error);

      let errorMessage = "Failed to register wallet";
      if (error.reason) {
        errorMessage = error.reason;
      } else if (error.response?.data?.error) {
        errorMessage = error.response.data.error;
      } else if (error.message) {
        errorMessage = error.message;
      }

      toast({
        title: "Registration Failed",
        description: errorMessage,
        variant: "destructive"
      });
    } finally {
      setLoading(false);
    }
  };
  
  return (
    <div className="min-h-screen bg-gradient-to-br from-background via-background to-primary/5 flex items-center justify-center px-4">
      <Card className="w-full max-w-md p-8 bg-card/95 backdrop-blur-sm border-primary/20 shadow-2xl animate-scale-in">
        <div className="text-center mb-8">
          <div className="w-20 h-20 bg-gradient-to-br from-primary to-primary/60 rounded-full mx-auto mb-4 flex items-center justify-center shadow-lg shadow-primary/30">
            <svg className="w-10 h-10 text-primary-foreground" fill="none" viewBox="0 0 24 24" stroke="currentColor">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M3 10h18M7 15h1m4 0h1m-7 4h12a3 3 0 003-3V8a3 3 0 00-3-3H6a3 3 0 00-3 3v8a3 3 0 003 3z" />
            </svg>
          </div>
          <h1 className="text-3xl font-bold mb-2 bg-gradient-to-r from-primary to-primary/60 bg-clip-text text-transparent">
            Welcome to Crypto Dashboard
          </h1>
          <p className="text-muted-foreground">
            Connect your wallet to start trading
          </p>
        </div>
        
        <Button 
          className="w-full mb-4 h-12 text-base font-semibold shadow-lg shadow-primary/30 hover:shadow-xl hover:shadow-primary/40 transition-all duration-300 hover:scale-[1.02]"
          onClick={handleConnect}
          disabled={loading}
        >
          {loading ? "Connecting..." : "Connect Wallet"}
        </Button>
        
        <div className="relative my-6">
          <div className="absolute inset-0 flex items-center">
            <div className="w-full border-t border-border"></div>
          </div>
          <div className="relative flex justify-center text-xs uppercase">
            <span className="bg-card px-2 text-muted-foreground">Or</span>
          </div>
        </div>
        
        <Button
          variant="outline"
          onClick={handleAutoRegister}
          disabled={loading}
          className="w-full h-12 text-base font-semibold border-primary/30 hover:bg-primary/10 hover:border-primary/50 transition-all duration-300 hover:scale-[1.02]"
        >
          {loading ? "Processing..." : "Auto-Register and Connect"}
        </Button>
        
        <p className="text-center text-xs text-muted-foreground mt-6">
          By connecting, you agree to our Terms of Service
        </p>
      </Card>
    </div>
  );
};

export default ConnectWallet;