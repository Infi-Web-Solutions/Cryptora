// === Connect to Ethereum Network ===
// Using Sepolia testnet (same as your Python setup)
const RPC_URL = process.env.ETHEREUM_RPC_URL || 'https://eth-sepolia.g.alchemy.com/v2/N0adIqZubpwEje_0URf5i';
const provider = new ethers.JsonRpcProvider(RPC_URL);

// === Create Wallet and Contract Instances ===
let wallet;
let contract;
let contractWithSigner;

try {
  // Create wallet instance
  wallet = new ethers.Wallet(PRIVATE_KEY, provider);
  
  // Read-only contract instance
  contract = new ethers.Contract(CONTRACT_ADDRESS, abi, provider);
  
  // Contract instance with signer (for write operations)
  contractWithSigner = new ethers.Contract(CONTRACT_ADDRESS, abi, wallet);
  
  console.log('[INFO] Successfully initialized contract connection');
  console.log(`[INFO] Wallet Address: ${WALLET_ADDRESS}`);
  console.log(`[INFO] Contract Address: ${CONTRACT_ADDRESS}`);
} catch (error) {
  console.error('[ERROR] Failed to initialize contract:', error.message);
  wallet = null;
  contract = null;
  contractWithSigner = null;
}

// === Debug Function: Check Connection ===
async function checkConnection() {
  try {
    const network = await provider.getNetwork();
    console.log(`[INFO] Connected to network: ${network.name} (Chain ID: ${network.chainId})`);
    
    // Check if wallet has balance
    const balance = await provider.getBalance(WALLET_ADDRESS);
    console.log(`[INFO] Wallet balance: ${ethers.formatEther(balance)} ETH`);
    
    // Check contract admin
    const adminAddress = await contract.admin();
    console.log(`[DEBUG] Contract admin address: ${adminAddress}`);
    console.log(`[DEBUG] Backend WALLET_ADDRESS: ${WALLET_ADDRESS}`);
    
    if (adminAddress.toLowerCase() !== WALLET_ADDRESS.toLowerCase()) {
      console.log('[WARNING] Backend wallet is NOT the contract admin. Admin-only functions will fail.');
    } else {
      console.log('[INFO] Backend wallet IS the contract admin. Admin-only functions should work.');
    }
    
    return true;
  } catch (error) {
    console.error('[ERROR] Connection check failed:', error.message);
    return false;
  }
}

// === Debug Function: Admin Register Check ===
async function debugAdminRegister(userAddress) {
  try {
    // Check if user is already registered
    const isRegistered = await contract.registered(userAddress);
    console.log(`[DEBUG] User ${userAddress} registered status: ${isRegistered}`);
    
    // Estimate gas for adminRegister
    try {
      const gasEstimate = await contractWithSigner.adminRegister.estimateGas(userAddress);
      console.log(`[DEBUG] Gas estimate for adminRegister: ${gasEstimate.toString()}`);
    } catch (gasError) {
      console.error(`[ERROR] Gas estimation failed for adminRegister(${userAddress}):`, gasError.message);
    }
  } catch (error) {
    console.error(`[ERROR] Debug admin register failed:`, error.message);
  }
}

